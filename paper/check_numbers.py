# 서로 어긋나면 안 되는 것 (원고 안 일관성)
def _retracted(*vals):
    """철회한 값 하나에서 **원고가 쓸 수 있는 표기를 전부** 만든다.

    **손으로 적은 가드가 반올림 때문에 새어 나갔다.** `-6.898` 만 막았는데
    원고는 `-6.90` 으로 반올림해 써서 가드가 0 회로 통과했고, 철회한 값이
    7.2 절에 살아남았다. CLAUDE.md 코드 관례가 같은 병을 이미 적어 뒀다 ---
    *"격자값은 정본 부호화 함수 하나에서 나오게 한다. 따로 만들면 반올림이
    갈려 조용히 어긋난다."* 이 검사기의 `옛 격차 3.92` 항목이 바로 그
    이유로 생겼는데 **이번 가드만 그 교훈 없이 지어졌다.**

    소수 2~3 자리만 만든다. 1 자리까지 가면 무관한 값에 걸린다.
    """
    out = set()
    for v in vals:
        for nd in (3, 2):
            out.add(("%.*f" % (nd, v)).replace(".", "\\."))
    return "|".join(sorted(out))


