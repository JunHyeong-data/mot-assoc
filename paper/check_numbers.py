def main(p):
    t = io.open(p, encoding="utf-8").read()
    bad = 0

    print("=" * 78)
    print("핵심 수치가 원고에 있는가")
    print("=" * 78)
    for name, s, src in MUST:
        n = t.count(s)
        ok = n >= 1
        bad += (not ok)
        print("  %-20s %-12s %2d회  %-28s %s"
              % (name, s, n, src, "" if ok else "!! 없다"))

    print()
    print("=" * 78)
    print("원고 안에서 일관된가")
    print("=" * 78)
    for name, pat, want, why in PAIRS:
        n = len(re.findall(pat, t))
        ok = (n == want)
        bad += (not ok)
        print("  %-16s %2d회 (기대 %d)  %-34s %s"
              % (name, n, want, why, "" if ok else "!! 어긋남"))

    print()
    print("=== 문제 %d 건 ===" % bad)
    return 1 if bad else 0


